using UnityEngine;

public class PersistirHUD : MonoBehaviour
{
    public static PersistirHUD Instancia { get; private set; }

    private void Awake()
    {
        if (Instancia != null && Instancia != this)
        {
            Destroy(gameObject);
            return;
        }

        Instancia = this;
        DontDestroyOnLoad(gameObject);
    }
}